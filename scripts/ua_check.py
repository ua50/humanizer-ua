"""Перевірка українського тексту за правилами humanizer-ua. Евристика, не детектор ШІ."""
import re, sys

STAMPS = ["з метою", "в рамках", "у рамках", "варто зазначити", "варто відзначити",
          "важливо підкреслити", "слід зазначити", "необхідно зазначити", "ключов",
          "комплексн", "всебічн", "всеосяжн", "безперечно", "відіграє важливу роль",
          "відіграє ключову роль", "має велике значення", "у сучасному світі",
          "на сьогоднішній день", "здійснювати", "здійснити", "здійснення",
          "забезпечити надання", "забезпечення", "провести аналіз", "проведення",
          "надати можливість", "являє собою", "є не просто", "не лише", "а й ",
          "сподіваюся, це допоможе", "чудове питання", "давайте розглянемо"]
RUSISMS = {"на протязі": "протягом", "приймати участь": "брати участь",
           "приймає участь": "бере участь", "являється": "є", "являються": "є",
           "в якості": "як", "згідно наказу": "згідно з наказом",
           "згідно договору": "згідно з договором", "співпадає": "збігається",
           "слідуючий": "наступний", "на рахунок": "щодо", "приймати міри": "вживати заходів",
           "вірно": "правильно", "любий": "будь-який", "по причині": "через",
           "у відповідності з": "відповідно до", "в залежності від": "залежно від",
           "дякуючи": "завдяки", "являтися": "бути"}
NOMIN = re.compile(r"\b\w+(?:ння|ення|ання|іння|ування|ація|яція)\b", re.I)
PASSIVE = re.compile(r"\b\w+(?:ється|ується|юється|иться|ються|уються|яться|аться)\b", re.I)
WORD = re.compile(r"[^\W\d_][\w'’ʼ\-]*|\d[\d,.\s]*\d|\d", re.U)

def main(path, limit=25):
    text = open(path, encoding="utf-8").read()
    low = text.lower()
    found = 0
    sents = [s.strip() for s in re.split(r"(?<=[.?!:])\s+|\n+", text) if s.strip()]
    for s in sents:
        n = len(WORD.findall(s))
        if n > limit:
            found += 1; print(f"[Б1] {n} слів: {s[:120]}")
        if len(NOMIN.findall(s)) >= 3:
            found += 1; print(f"[Б2] віддієслівні іменники ({', '.join(NOMIN.findall(s)[:4])}): {s[:100]}")
        if len(PASSIVE.findall(s)) >= 2:
            found += 1; print(f"[Б3] кілька безособових форм: {s[:100]}")
    for st in STAMPS:
        c = low.count(st)
        if c: found += 1; print(f"[Л1] «{st.strip()}» × {c}")
    for r, ok in RUSISMS.items():
        c = low.count(r)
        if c: found += 1; print(f"[Л3] «{r}» × {c} → {ok}")
    if ";" in text: found += 1; print(f"[О3] крапка з комою × {text.count(';')}")
    d = text.count("—")
    if d > max(2, len(sents) // 10): found += 1; print(f"[О1] забагато тире: {d} (перевір, чи кожне потрібне за правописом)")
    if re.search(r"[“”\"]", text): found += 1; print("[О2] лапки не «» (крім коду та URL)")
    words = len(WORD.findall(text))
    print(f"{path}: {found} знахідок | {len(sents)} речень, у середньому {words/max(1,len(sents)):.1f} слова")

if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    main(args[0], 20 if "--strict" in sys.argv else 25)
